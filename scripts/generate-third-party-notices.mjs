// Regenerates THIRD_PARTY_LICENSES.md — the license texts of everything the
// published artifact redistributes (packages compiled into the CLI bundle) plus
// the declared runtime dependencies. Run after dependency changes:
//
//   node scripts/generate-third-party-notices.mjs
//
// The bundled set is discovered from an esbuild metafile (not hand-maintained),
// so the notice file can never drift from what the bundle actually contains.

import { execSync } from "node:child_process";
import { readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const cliDir = join(root, "packages/cli");

// 1. Build with a metafile and collect the bundled package names.
execSync("pnpm exec tsup --metafile", { cwd: cliDir, stdio: "ignore" });
const metaPath = join(cliDir, "dist/metafile-esm.json");
const meta = JSON.parse(readFileSync(metaPath, "utf8"));
rmSync(metaPath);
const bundled = new Set();
for (const input of Object.keys(meta.inputs)) {
  const m = input.match(/node_modules\/(?:\.pnpm\/[^/]+\/node_modules\/)?((?:@[^/]+\/)?[^/]+)/);
  if (m) bundled.add(m[1]);
}

// 2. Declared runtime dependencies of the published package (installed from
// the registry by the user; listed for completeness, obligations differ).
const cliManifest = JSON.parse(readFileSync(join(cliDir, "package.json"), "utf8"));
const runtime = Object.keys(cliManifest.dependencies ?? {});

function findPackageDir(name) {
  const base = join(root, "node_modules/.pnpm");
  const prefix = `${name.replace("/", "+")}@`;
  const dir = readdirSync(base).find((d) => d.startsWith(prefix));
  return dir ? join(base, dir, "node_modules", name) : null;
}

function licenseInfo(name) {
  const dir = findPackageDir(name);
  if (!dir) throw new Error(`cannot locate installed package: ${name}`);
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const licenseFile = readdirSync(dir).find((f) => /^licen[cs]e/i.test(f));
  const text = licenseFile ? readFileSync(join(dir, licenseFile), "utf8").trim() : null;
  return { name, version: pkg.version, license: pkg.license ?? "UNKNOWN", text };
}

function section(title, note, names) {
  const lines = [`## ${title}`, "", note, ""];
  for (const name of [...names].sort()) {
    const info = licenseInfo(name);
    lines.push(`### ${info.name}@${info.version} — ${info.license}`, "");
    if (info.text) {
      lines.push("```", info.text, "```", "");
    } else {
      lines.push(
        `_No license file shipped in the package; license declared as ${info.license}._`,
        "",
      );
    }
  }
  return lines;
}

const out = [
  "# Third-party licenses",
  "",
  "Generated by `scripts/generate-third-party-notices.mjs` — do not edit by hand.",
  "",
  ...section(
    "Bundled packages",
    "Compiled into the published `dist/` bundle (redistributed with this software).",
    bundled,
  ),
  ...section(
    "Runtime dependencies",
    "Declared dependencies installed from the npm registry alongside this package.",
    runtime,
  ),
].join("\n");

writeFileSync(join(root, "THIRD_PARTY_LICENSES.md"), `${out}\n`);
const count = bundled.size + runtime.length;
console.log(
  `THIRD_PARTY_LICENSES.md written (${count} packages: ${bundled.size} bundled, ${runtime.length} runtime)`,
);
